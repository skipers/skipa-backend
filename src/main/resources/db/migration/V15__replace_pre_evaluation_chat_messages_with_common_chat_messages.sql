create table evaluation_chat_messages (
    id bigint generated by default as identity,
    target_type varchar(30) not null,
    target_id bigint not null,
    user_id bigint not null,
    role varchar(20) not null,
    content text not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null,
    constraint pk_evaluation_chat_messages primary key (id),
    constraint fk_evaluation_chat_messages_user foreign key (user_id) references users (id)
);

insert into evaluation_chat_messages (
    target_type,
    target_id,
    user_id,
    role,
    content,
    created_at,
    updated_at
)
select
    'PRE_EVALUATION',
    pcm.pre_evaluation_id,
    pe.user_id,
    pcm.role,
    pcm.content,
    pcm.created_at,
    pcm.updated_at
from pre_evaluation_chat_messages pcm
join pre_evaluations pe on pe.id = pcm.pre_evaluation_id;

drop table pre_evaluation_chat_messages;

create index idx_evaluation_chat_messages_target
    on evaluation_chat_messages (target_type, target_id);

create index idx_evaluation_chat_messages_user_id
    on evaluation_chat_messages (user_id);
